DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_type WHERE typname = 'support_ticket_status'
    ) THEN
        CREATE TYPE public.support_ticket_status AS ENUM ('open', 'closed');
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_type WHERE typname = 'support_side'
    ) THEN
        CREATE TYPE public.support_side AS ENUM ('buyer', 'supplier');
    END IF;
END $$;

ALTER TYPE public.notification_type ADD VALUE IF NOT EXISTS 'support';

CREATE TABLE IF NOT EXISTS public.support_tickets (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    side public.support_side NOT NULL,
    status public.support_ticket_status NOT NULL DEFAULT 'open',
    assigned_admin_id integer REFERENCES public.users(id) ON DELETE SET NULL,
    last_message_at timestamp with time zone,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    closed_at timestamp with time zone
);

CREATE UNIQUE INDEX IF NOT EXISTS support_tickets_one_open_per_user_side_uidx
    ON public.support_tickets (user_id, side)
    WHERE status = 'open';

CREATE INDEX IF NOT EXISTS support_tickets_status_last_message_idx
    ON public.support_tickets (status, last_message_at DESC NULLS LAST);

CREATE TABLE IF NOT EXISTS public.support_messages (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id integer NOT NULL REFERENCES public.support_tickets(id) ON DELETE CASCADE,
    sender_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    text text NOT NULL DEFAULT '',
    status public.message_delivery_status NOT NULL DEFAULT 'sent',
    delivered_at timestamp with time zone,
    viewed_at timestamp with time zone,
    created_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS support_messages_ticket_id_idx
    ON public.support_messages (ticket_id, created_at);

CREATE TABLE IF NOT EXISTS public.support_message_attachments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id integer NOT NULL REFERENCES public.support_messages(id) ON DELETE CASCADE,
    file_name character varying(255) NOT NULL,
    file_url character varying(500) NOT NULL,
    file_type character varying(100) NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS support_message_attachments_message_id_uidx
    ON public.support_message_attachments (message_id);

INSERT INTO public.permissions (name, resource, action)
SELECT v.name, v.resource, v.action
FROM (
    VALUES
        ('admin_support.view', 'admin_support', 'view'),
        ('admin_support.update', 'admin_support', 'update')
) AS v(name, resource, action)
WHERE NOT EXISTS (SELECT 1 FROM public.permissions p WHERE p.name = v.name);

INSERT INTO public.role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM public.roles r
JOIN public.permissions p ON p.resource = 'admin_support'
WHERE r.name IN ('admin', 'superadmin', 'moderator')
  AND NOT EXISTS (
      SELECT 1 FROM public.role_permissions rp
      WHERE rp.role_id = r.id AND rp.permission_id = p.id
  );
